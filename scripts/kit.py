"""Canonical sources and deterministic adapters for Engineering Agent Kit."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROVIDERS = ("codex", "claude", "cursor")
ROLE_NAME = re.compile(r"^delivery-[a-z][a-z0-9-]*$")
GENERATED = "<!-- Generated by scripts/render_adapters.py from agents/*.md and roles.json. Do not edit. -->"


def load_roles(root: Path = ROOT) -> dict[str, dict]:
    roles = json.loads((root / "agents" / "roles.json").read_text(encoding="utf-8"))
    if not roles:
        raise ValueError("At least one agent role is required")
    for name, meta in roles.items():
        if not ROLE_NAME.fullmatch(name):
            raise ValueError(f"Invalid role name: {name!r}")
        if not isinstance(meta.get("description"), str) or not meta["description"]:
            raise ValueError(f"Missing description for {name}")
        if not isinstance(meta.get("readonly"), bool):
            raise ValueError(f"Missing readonly flag for {name}")
        if not (root / "agents" / f"{name}.md").is_file():
            raise ValueError(f"Missing canonical instructions: {name}.md")
    return roles


def make_agent(provider: str, name: str, meta: dict, instructions: str) -> str:
    if provider not in PROVIDERS:
        raise ValueError(f"Unsupported provider: {provider}")
    desc = meta["description"]
    readonly = meta["readonly"]
    if provider == "codex":
        # TOML basic strings accept the JSON double-quoted string escape syntax.
        # Deliberately no sandbox_mode: Codex subagents inherit their parent's policy.
        return ("# Generated by scripts/render_adapters.py. Do not edit.\n"
                f"name = {json.dumps(name)}\n"
                f"description = {json.dumps(desc)}\n"
                f"developer_instructions = {json.dumps(instructions, ensure_ascii=False)}\n")
    header = ["---", f"name: {name}", f"description: {json.dumps(desc)}", "model: inherit"]
    if provider == "claude":
        if readonly:
            header.append("tools: Read, Grep, Glob")
        else:
            header.append("tools: Read, Grep, Glob, Edit, Write, Bash")
    else:
        header.append(f"readonly: {'true' if readonly else 'false'}")
    return "\n".join(header + ["---", "", GENERATED, "", instructions.rstrip(), ""])


def generated_adapters(root: Path = ROOT) -> dict[str, bytes]:
    rendered: dict[str, bytes] = {}
    roles = load_roles(root)
    for provider in PROVIDERS:
        for name, meta in roles.items():
            body = (root / "agents" / f"{name}.md").read_text(encoding="utf-8").strip() + "\n"
            ext = ".toml" if provider == "codex" else ".md"
            path = f"adapters/{provider}/agents/{name}{ext}"
            rendered[path] = make_agent(provider, name, meta, body).encode("utf-8")
    return rendered


def skill_files(root: Path = ROOT) -> dict[str, bytes]:
    base = root / "skills" / "software-delivery"
    if not (base / "SKILL.md").is_file():
        raise ValueError("Missing software-delivery SKILL.md")
    return {path.relative_to(base).as_posix(): path.read_bytes() for path in sorted(base.rglob("*")) if path.is_file()}


def deployment_files(target_root: Path, provider: str, root: Path = ROOT) -> dict[Path, bytes]:
    if provider not in PROVIDERS:
        raise ValueError(provider)
    if provider == "codex":
        skill_dest = target_root / ".agents" / "skills" / "software-delivery"
    elif provider == "claude":
        skill_dest = target_root / ".claude" / "skills" / "software-delivery"
    else:
        skill_dest = target_root / ".cursor" / "skills" / "software-delivery"
    outputs = {skill_dest / relative: data for relative, data in skill_files(root).items()}
    for path, content in generated_adapters(root).items():
        if path.startswith(f"adapters/{provider}/"):
            relative = Path(path).relative_to(f"adapters/{provider}")
            outputs[target_root / f".{provider if provider != 'claude' else 'claude'}" / relative] = content
    return outputs
